CREATE TABLE circuito_ciudad (
  circuito_id   INTEGER NOT NULL REFERENCES circuito(circuito_id),
  ciudad_id     INTEGER NOT NULL REFERENCES ciudad(ciudad_id),
  PRIMARY KEY (circuito_id, ciudad_id)
);

CREATE TABLE pasaje (
  pasaje_id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  descripcion         VARCHAR(200),
  horario_vuelo       TIMESTAMP,
  precio              NUMERIC(10,2) NOT NULL DEFAULT 0,
  millas_otorgadas    INTEGER DEFAULT 0 NOT NULL,
  aero_salida_id      VARCHAR(4) NOT NULL REFERENCES aeropuerto(codigo),
  aero_llegada_id     VARCHAR(4) NOT NULL REFERENCES aeropuerto(codigo)
