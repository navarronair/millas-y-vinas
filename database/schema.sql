CREATE TABLE reserva (
  reserva_id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  fecha_reserva        DATE DEFAULT CURRENT_DATE NOT NULL,
  codigo_vuelo         VARCHAR(20),
  millas_generadas     INTEGER DEFAULT 0,
  cliente_dni          VARCHAR(15) NOT NULL REFERENCES cliente(dni),
  agencia_id           INTEGER NOT NULL REFERENCES agencia(agencia_id),
  pasaje_id            INTEGER REFERENCES pasaje(pasaje_id),
  hotel_id             INTEGER REFERENCES hotel(hotel_id),
  circuito_id          INTEGER REFERENCES circuito(circuito_id),
  CONSTRAINT ck_reserva_tipo CHECK (
    pasaje_id IS NOT NULL OR hotel_id IS NOT NULL OR circuito_id IS NOT NULL
