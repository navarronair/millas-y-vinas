-- ===== Ubicación (compartida) =====
CREATE TABLE pais (
  codigo   CHAR(3) PRIMARY KEY,
  nombre   VARCHAR(80) NOT NULL
);

CREATE TABLE provincia (
  provincia_id   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre         VARCHAR(100) NOT NULL,
  pais_codigo    CHAR(3) NOT NULL REFERENCES pais(codigo)
);

CREATE TABLE ciudad (
  ciudad_id      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre         VARCHAR(100) NOT NULL,
  provincia_id   INTEGER NOT NULL REFERENCES provincia(provincia_id)
);

CREATE TABLE aeropuerto (
  codigo             VARCHAR(4) PRIMARY KEY,
  nombre             VARCHAR(100) NOT NULL,
  cant_vuelos_prom   INTEGER,
  pais_codigo        CHAR(3) NOT NULL REFERENCES pais(codigo)
);

-- ===== Cliente y fidelización (integración) =====
CREATE TABLE categoria_cliente (
  categoria_id       INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre             VARCHAR(30) NOT NULL,
  nivel              INTEGER NOT NULL,
  millas_minimas     INTEGER NOT NULL,
  descuento_pct      NUMERIC(5,2) DEFAULT 0 NOT NULL,
  acceso_exclusivo   CHAR(1) DEFAULT 'N' CHECK (acceso_exclusivo IN ('S','N')),
  CONSTRAINT uk_categoria_nivel UNIQUE (nivel)
);

CREATE TABLE cliente (
  dni                  VARCHAR(15) PRIMARY KEY,
  nombre               VARCHAR(60) NOT NULL,
  apellido             VARCHAR(60) NOT NULL,
  email                VARCHAR(120) UNIQUE NOT NULL,
  telefono             VARCHAR(30),
  password_hash        VARCHAR(255) NOT NULL,
  millas_acumuladas    INTEGER DEFAULT 0 NOT NULL,
  categoria_id         INTEGER NOT NULL REFERENCES categoria_cliente(categoria_id)
);

-- ===== Turismo =====
CREATE TABLE agencia (
  agencia_id        INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  cant_empleados     INTEGER CHECK (cant_empleados >= 0),
  direccion_fisica   VARCHAR(200) NOT NULL
);

CREATE TABLE mayorista (
  mayorista_id              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre                    VARCHAR(120) NOT NULL,
  facturacion_prom_anual    NUMERIC(14,2)
