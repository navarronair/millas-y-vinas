CREATE TABLE agencia_mayorista (
  agencia_id     INTEGER NOT NULL REFERENCES agencia(agencia_id),
  mayorista_id   INTEGER NOT NULL REFERENCES mayorista(mayorista_id),
  PRIMARY KEY (agencia_id, mayorista_id)
);

CREATE TABLE hotel (
  hotel_id       INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre         VARCHAR(100) NOT NULL,
  categoria      INTEGER,
  direccion      VARCHAR(200),
  precio_noche   NUMERIC(10,2) NOT NULL DEFAULT 0,
  ciudad_id      INTEGER NOT NULL REFERENCES ciudad(ciudad_id)
);

CREATE TABLE circuito (
  circuito_id                 INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  denominacion                VARCHAR(120) NOT NULL,
  cant_personas_anual_prom    INTEGER,
  precio                      NUMERIC(10,2) NOT NULL DEFAULT 0
