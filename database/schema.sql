-- 1) Recalcular categoría del cliente según sus millas
CREATE OR REPLACE FUNCTION prc_actualizar_categoria(p_dni VARCHAR)
RETURNS VOID AS $$
DECLARE
  v_categoria_id INTEGER;
BEGIN
  SELECT categoria_id INTO v_categoria_id
  FROM categoria_cliente
  WHERE millas_minimas <= (SELECT millas_acumuladas FROM cliente WHERE dni = p_dni)
  ORDER BY millas_minimas DESC
  FETCH FIRST 1 ROW ONLY;

  UPDATE cliente SET categoria_id = v_categoria_id WHERE dni = p_dni;
END;
$$ LANGUAGE plpgsql;

-- 2) BEFORE INSERT en reserva: copia las millas del pasaje (si hay)
CREATE OR REPLACE FUNCTION trg_reserva_bi_fn()
RETURNS TRIGGER AS $$
DECLARE
  v_millas INTEGER;
BEGIN
  IF NEW.pasaje_id IS NOT NULL THEN
    SELECT millas_otorgadas INTO v_millas FROM pasaje WHERE pasaje_id = NEW.pasaje_id;
    NEW.millas_generadas := v_millas;
  ELSE
    NEW.millas_generadas := 0;
  END IF;
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_reserva_bi
BEFORE INSERT ON reserva
FOR EACH ROW EXECUTE FUNCTION trg_reserva_bi_fn();

-- 3) AFTER INSERT en reserva: suma millas al cliente y recalcula categoría
CREATE OR REPLACE FUNCTION trg_reserva_ai_fn()
RETURNS TRIGGER AS $$
BEGIN
  IF NEW.millas_generadas > 0 THEN
    UPDATE cliente
    SET millas_acumuladas = millas_acumuladas + NEW.millas_generadas
    WHERE dni = NEW.cliente_dni;

    PERFORM prc_actualizar_categoria(NEW.cliente_dni);
  END IF;
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_reserva_ai
AFTER INSERT ON reserva
FOR EACH ROW EXECUTE FUNCTION trg_reserva_ai_fn();

-- 4) BEFORE INSERT en linea_venta_vino: valida acceso al catálogo exclusivo
CREATE OR REPLACE FUNCTION trg_linea_venta_bi_fn()
RETURNS TRIGGER AS $$
DECLARE
  v_categoria_min      INTEGER;
  v_cliente_dni        VARCHAR(15);
  v_nivel_cliente      INTEGER;
  v_nivel_requerido    INTEGER;
BEGIN
  SELECT categoria_minima_id INTO v_categoria_min FROM vino WHERE vino_id = NEW.vino_id;

  IF v_categoria_min IS NOT NULL THEN
    SELECT cliente_dni INTO v_cliente_dni FROM venta_vino WHERE venta_id = NEW.venta_id;

    SELECT cc.nivel INTO v_nivel_cliente
    FROM cliente c JOIN categoria_cliente cc ON c.categoria_id = cc.categoria_id
    WHERE c.dni = v_cliente_dni;

    SELECT nivel INTO v_nivel_requerido FROM categoria_cliente WHERE categoria_id = v_categoria_min;

    IF v_nivel_cliente < v_nivel_requerido THEN
      RAISE EXCEPTION 'El cliente no alcanza la categoria minima para comprar este vino exclusivo.';
    END IF;
  END IF;
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_linea_venta_bi
BEFORE INSERT ON linea_venta_vino
FOR EACH ROW EXECUTE FUNCTION trg_linea_venta_bi_fn();

-- 5) Registrar venta de vino aplicando el descuento de categoría
--    (la Flask app la llama vía supabase.rpc(...))
CREATE OR REPLACE FUNCTION prc_registrar_venta_vino(
  p_cliente_dni VARCHAR,
  p_vino_id INTEGER,
  p_cantidad INTEGER
) RETURNS INTEGER AS $$
DECLARE
  v_venta_id       INTEGER;
  v_descuento_pct  NUMERIC;
  v_precio         NUMERIC;
  v_subtotal       NUMERIC;
  v_stock_actual   INTEGER;
BEGIN
  SELECT cantidad INTO v_stock_actual FROM stock WHERE vino_id = p_vino_id;
  IF v_stock_actual IS NULL OR v_stock_actual < p_cantidad THEN
    RAISE EXCEPTION 'No hay stock suficiente de este vino.';
  END IF;

  SELECT cc.descuento_pct INTO v_descuento_pct
  FROM cliente c JOIN categoria_cliente cc ON c.categoria_id = cc.categoria_id
  WHERE c.dni = p_cliente_dni;

  SELECT precio INTO v_precio FROM vino WHERE vino_id = p_vino_id;
  v_subtotal := v_precio * p_cantidad * (1 - v_descuento_pct / 100);

  INSERT INTO venta_vino (cliente_dni, fecha, total, descuento_aplicado)
  VALUES (p_cliente_dni, CURRENT_DATE, v_subtotal, v_descuento_pct)
  RETURNING venta_id INTO v_venta_id;

  INSERT INTO linea_venta_vino (venta_id, vino_id, cantidad, precio_unitario)
  VALUES (v_venta_id, p_vino_id, p_cantidad, v_precio);

  UPDATE stock SET cantidad = cantidad - p_cantidad, ultima_actualizacion = CURRENT_DATE
  WHERE vino_id = p_vino_id;

  INSERT INTO movimiento_stock (vino_id, tipo, cantidad)
  VALUES (p_vino_id, 'SALIDA', p_cantidad);

  RETURN v_venta_id;
END;
$$ LANGUAGE plpgsql;

-- 6) Registrar una reserva (turismo) - inserta y deja que los triggers
--    de millas hagan su trabajo. La Flask app la llama vía RPC.
CREATE OR REPLACE FUNCTION prc_registrar_reserva(
  p_cliente_dni VARCHAR,
  p_agencia_id INTEGER,
  p_pasaje_id INTEGER,
  p_hotel_id INTEGER,
  p_circuito_id INTEGER
) RETURNS INTEGER AS $$
DECLARE
  v_reserva_id INTEGER;
BEGIN
  INSERT INTO reserva (cliente_dni, agencia_id, pasaje_id, hotel_id, circuito_id)
  VALUES (p_cliente_dni, p_agencia_id, p_pasaje_id, p_hotel_id, p_circuito_id)
  RETURNING reserva_id INTO v_reserva_id;

  RETURN v_reserva_id;
END;
$$ LANGUAGE plpgsql;

